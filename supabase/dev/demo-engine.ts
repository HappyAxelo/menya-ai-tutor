// Demonstration of the tutoring engine with the REAL model (Groq) and a local
// database: three student-style problems (calculus, programming, electronics).
// Each student makes a classic mistake, repeats it or gets stuck, recovers, and
// then gets an unseen "Check yourself" problem to solve alone. Writes what
// actually happened to docs/DEMO.md. Needs GROQ_API_KEY (reads ../menya/.env).
//   cd supabase && node dev/demo-engine.ts
import { readFileSync, existsSync, writeFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
import { freshDb, createUser } from "../tests/db.ts";
import { pgRepo } from "../tests/pgRepo.ts";
import { handleTutor } from "../functions/_shared/tutorService.ts";
import { buildProviders } from "../functions/_shared/providers.ts";
import { objective as objectiveInfo, type Item } from "../functions/_shared/engine/bank.ts";

const envFile = new URL("../../menya/.env", import.meta.url);
if (!process.env.GROQ_API_KEY && existsSync(envFile)) {
  for (const line of readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const m = /^\s*GROQ_API_KEY\s*=\s*(.+)\s*$/.exec(line);
    if (m) process.env.GROQ_API_KEY = m[1].replace(/^["']|["']$/g, "");
  }
}
if (!process.env.GROQ_API_KEY) throw new Error("Set GROQ_API_KEY");

const db = await freshDb();
let lastTurn: Record<string, unknown> = {};
const deps = {
  repo: pgRepo(db), providers: buildProviders({ GROQ_API_KEY: process.env.GROQ_API_KEY }),
  log: (e: Record<string, unknown>) => { if (e.event === "engine_turn") lastTurn = e; },
};
const sleep = (ms: number) => new Promise(r => setTimeout(r, ms));
const out: string[] = [];
const md = (s = "") => { out.push(s); console.log(s); };

type Step = { label: string; action?: string; say?: (item: Item) => string; stuck?: string };

async function demo(title: string, objectiveId: string, opener: string, steps: Step[]) {
  if (process.env.ONLY && !title.startsWith(`${process.env.ONLY}.`)) return;
  md(`## ${title}`); md();
  const user = await createUser(db);
  let sessionId: string | null = null;
  let item: Item | null = null;
  const send = async (body: Record<string, unknown>) => {
    for (let retry = 0; retry < 4; retry++) {
      await sleep(retry ? 15000 : 9000);   // student pace; stay well inside free-tier limits
      const res = await handleTutor(deps, user, { requestId: randomUUID(), sessionId, language: "English", ...body });
      if (res.status === 200) return res;
      console.log(`  (${res.body.error}; retrying)`);
    }
    throw new Error("the model was unavailable");
  };

  // The learner's first message; the conversation's topic is the objective being practised.
  let res = await send({ action: "message", message: opener });
  sessionId = res.body.sessionId as string;
  await db.query("update public.tutoring_sessions set objective = $1 where id = $2", [objectiveId, sessionId]);
  md(`**Student:** ${opener}`); md();
  md(`**Menya** _(${(res.body.engine as any).state})_: ${(res.body.reply as any).message}`); md();

  for (const step of steps) {
    const body: Record<string, unknown> = step.say ? { action: "message", message: step.say(item!) } : { action: step.action, stuck: step.stuck };
    res = await send(body);
    const engine = res.body.engine as any, reply = res.body.reply as any;
    const row = (await db.query<any>("select item from public.session_items where session_id = $1", [sessionId])).rows[0];
    if (row) item = row.item;
    md(`### ${step.label}`); md();
    if (step.say) md(`**Student:** ${body.message}`);
    else md(`**Student:** _[${step.action}${step.stuck ? `: ${step.stuck}` : ""}]_`);
    md();
    md(`- **Server check:** ${engine.verified ?? "nothing to check (not an answer)"}${lastTurn.misconception ? ` · misconception: \`${lastTurn.misconception}\`` : ""}`);
    md(`- **Engine:** state \`${engine.state}\`${engine.hintLevel != null ? `, help level ${engine.hintLevel}` : ""} · why: ${lastTurn.rationale}`);
    if (engine.mastery) md(`- **Learning profile (${objectiveInfo(objectiveId)?.title}):** ${engine.mastery.status}, estimate ${engine.mastery.estimate}, solved alone ${engine.mastery.independent}`);
    md(); md("**Menya:**"); md(); md(reply.message); md();
  }
}

md("# Tutoring engine demonstration");
md();
md(`Generated by \`supabase/dev/demo-engine.ts\` on ${new Date().toISOString().slice(0, 10)} with the real model (Groq, free tier) and a local copy of the database. Every reply below is the model's actual output; the server checks, engine states and learning-profile lines are what the system recorded. Problems marked "Practice problem" and "Check yourself" come from the deterministic bank (\`engine/bank.ts\`), not from the model.`);
md();

const firstNumber = (i: Item, re: RegExp) => Number(re.exec(i.question)![1]);

// A wrong answer for a loop item: include range()'s stop value if the loop would reach it,
// otherwise ignore the step (both are misconceptions the bank recognises).
function wrongLoopSum(i: Item): number {
  const [a, b, c] = /range\((\d+), (\d+), (\d+)\)/.exec(i.question)!.slice(1).map(Number);
  let inc = 0; for (let k = a; k <= b; k += c) inc += k;
  if (inc !== Number(i.answer)) return inc;
  let all = 0; for (let k = a; k < b; k++) all += k;
  return all;
}

await demo("1. Calculus: the product rule", "calc.product_rule", "I have a calculus test next week and the product rule confuses me. Can we practise?", [
  { label: "A practice problem from the bank", action: "practice" },
  { label: "First attempt: the classic mistake (u'·v')", say: i => { const [, c, ns] = /= (\d*)x\^(\d)/.exec(i.question)!; const n = Number(ns), a = Number(c || 1); const dv = i.answer.split(" + ")[1].split("·")[1]; return `f'(x) = ${a * n}x^${n - 1} · ${dv.replace("exp(x)", "e^x")}`; } },
  { label: "The student is stuck on a step", action: "stuck", stuck: "step" },
  { label: "Second attempt, with working", say: i => `u = ${/= (\d*x\^\d)/.exec(i.question)![1]}, so u'v + uv' gives f'(x) = ${i.answer.replace(/exp\(x\)/g, "e^x").replace(/\^1(?!\d)/g, "")}` },
  { label: "Independent check: an unseen problem, no hints", action: "verify" },
  { label: "Solved alone", say: i => `Using the product rule: f'(x) = ${i.answer.replace(/exp\(x\)/g, "e^x").replace(/\^1(?!\d)/g, "")}` },
]);

await demo("2. Programming: tracing a loop", "prog.loop_tracing", "Our lecturer gives us code and asks what it prints. I keep getting these wrong.", [
  { label: "A practice problem from the bank", action: "practice" },
  { label: "First attempt: a classic range() mistake", say: i => `It prints ${wrongLoopSum(i)}` },
  { label: "The same mistake again", say: i => `I added them again and got ${wrongLoopSum(i)}` },
  { label: "Correct, with a trace", say: i => { const [a, b, c] = /range\((\d+), (\d+), (\d+)\)/.exec(i.question)!.slice(1).map(Number); const v: number[] = []; for (let k = a; k < b; k += c) v.push(k); return `i takes ${v.join(", ")} (the stop value is excluded), so total = ${v.reduce((x, y) => x + y, 0)}`; } },
  { label: "Independent check: an unseen problem, no hints", action: "verify" },
  { label: "Solved alone", say: i => { const [a, b, c] = /range\((\d+), (\d+), (\d+)\)/.exec(i.question)!.slice(1).map(Number); const v: number[] = []; for (let k = a; k < b; k += c) v.push(k); return `Values ${v.join(", ")}, sum ${v.reduce((x, y) => x + y, 0)}`; } },
]);

await demo("3. Electronics: resistors in series", "ee.series_circuits", "Can you help me with series circuits? I'm not sure which resistance to use.", [
  { label: "A practice problem from the bank", action: "practice" },
  { label: "First attempt: uses one resistor only", say: i => { const [R1, , V] = (i.question.match(/\d+(?= Ω| V)/g) ?? []).map(Number); return `I = V/R1 = ${V}/${R1} = ${Math.round((V / R1) * 10000) / 10} mA`; } },
  { label: "The student doesn't understand the idea", action: "stuck", stuck: "concept" },
  { label: "Correct, with working", say: i => { const [R1, R2, V] = (i.question.match(/\d+(?= Ω| V)/g) ?? []).map(Number); return `R = ${R1} + ${R2} = ${R1 + R2} Ω, I = ${V}/${R1 + R2} A = ${Math.round((V / (R1 + R2)) * 10000) / 10} mA`; } },
  { label: "Independent check: an unseen problem, no hints", action: "verify" },
  { label: "Solved alone", say: i => { const [R1, R2, V] = (i.question.match(/\d+(?= Ω| V)/g) ?? []).map(Number); return `Total ${R1 + R2} Ω, so I = ${V}/${R1 + R2} = ${Math.round((V / (R1 + R2)) * 10000) / 10} mA`; } },
]);

md("## What this shows, and what it does not");
md();
md("- The problems, reference answers and marking are deterministic; the misconception labels come from the wrong answers they produce, not from the model's guess.");
md("- After a guided solve, the learner gets an unseen problem and solves it without help; only that counts as independent evidence. Mastery would additionally need a later success after a break of at least two days (spaced review), which a single session cannot show.");
md("- The student's turns are scripted. This demonstrates the system's behaviour, not learning gains: those need the study in docs/EVALUATION_PLAN.md.");
writeFileSync(new URL(process.env.ONLY ? "../../docs/DEMO-part.md" : "../../docs/DEMO.md", import.meta.url), out.join("\n") + "\n");
console.log(`\nWrote docs/${process.env.ONLY ? "DEMO-part" : "DEMO"}.md`);
